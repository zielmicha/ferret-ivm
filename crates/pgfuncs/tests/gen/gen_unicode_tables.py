"""Generate src/unicode_tables.rs from PostgreSQL 17's Unicode headers.

Inputs (from the PostgreSQL REL_17_STABLE tree, Unicode 15.1):
  src/include/common/unicode_case_table.h
  src/include/common/unicode_category_table.h

Usage: python3 gen_unicode_tables.py <dir-with-headers> <output.rs>
"""
import re
import sys

src_dir, out_path = sys.argv[1], sys.argv[2]

case_h = open(f"{src_dir}/unicode_case_table.h").read()
cat_h = open(f"{src_dir}/unicode_category_table.h").read()

case_re = re.compile(
    r"\{0x([0-9a-f]+), \{\[CaseLower\] = 0x([0-9a-f]+),\[CaseTitle\] = 0x([0-9a-f]+),\[CaseUpper\] = 0x([0-9a-f]+)\}\}"
)
cases = [tuple(int(x, 16) for x in m.groups()) for m in case_re.finditer(case_h)]
assert len(cases) == int(re.search(r"case_map\[(\d+)\]", case_h).group(1))
for i in range(128):
    assert cases[i][0] == i
sparse = cases[128:]
assert all(sparse[i][0] < sparse[i + 1][0] for i in range(len(sparse) - 1))

CATS = {
    "PG_U_UNASSIGNED": 0, "PG_U_UPPERCASE_LETTER": 1, "PG_U_LOWERCASE_LETTER": 2,
    "PG_U_TITLECASE_LETTER": 3, "PG_U_MODIFIER_LETTER": 4, "PG_U_OTHER_LETTER": 5,
    "PG_U_NONSPACING_MARK": 6, "PG_U_ENCLOSING_MARK": 7, "PG_U_SPACING_MARK": 8,
    "PG_U_DECIMAL_NUMBER": 9, "PG_U_LETTER_NUMBER": 10, "PG_U_OTHER_NUMBER": 11,
    "PG_U_SPACE_SEPARATOR": 12, "PG_U_LINE_SEPARATOR": 13, "PG_U_PARAGRAPH_SEPARATOR": 14,
    "PG_U_CONTROL": 15, "PG_U_FORMAT": 16, "PG_U_PRIVATE_USE": 17, "PG_U_SURROGATE": 18,
    "PG_U_DASH_PUNCTUATION": 19, "PG_U_OPEN_PUNCTUATION": 20, "PG_U_CLOSE_PUNCTUATION": 21,
    "PG_U_CONNECTOR_PUNCTUATION": 22, "PG_U_OTHER_PUNCTUATION": 23, "PG_U_MATH_SYMBOL": 24,
    "PG_U_CURRENCY_SYMBOL": 25, "PG_U_MODIFIER_SYMBOL": 26, "PG_U_OTHER_SYMBOL": 27,
    "PG_U_INITIAL_PUNCTUATION": 28, "PG_U_FINAL_PUNCTUATION": 29,
}
PROPS = {
    "PG_U_PROP_ALPHABETIC": 1, "PG_U_PROP_LOWERCASE": 2, "PG_U_PROP_UPPERCASE": 4,
    "PG_U_PROP_CASED": 8, "PG_U_PROP_CASE_IGNORABLE": 16, "PG_U_PROP_WHITE_SPACE": 32,
    "PG_U_PROP_JOIN_CONTROL": 64, "PG_U_PROP_HEX_DIGIT": 128,
}

ascii_block = cat_h[cat_h.index("unicode_opt_ascii[128]"):cat_h.index("unicode_categories[")]
ascii_re = re.compile(r"\.category = (\w+),\s*\.properties = ([^\n]+)\n")
ascii = []
for m in ascii_re.finditer(ascii_block):
    cat = CATS[m.group(1)]
    props = 0
    for p in m.group(2).split("|"):
        p = p.strip()
        if p and p != "0":
            props |= PROPS[p]
    ascii.append((cat, props))
assert len(ascii) == 128, len(ascii)


def table(name):
    m = re.search(name + r"\[(\d+)\] =\s*\{(.*?)\n\};", cat_h, re.S)
    n = int(m.group(1))
    body = m.group(2)
    return n, body


n, body = table("unicode_categories")
cat_ranges = [(int(a, 16), int(b, 16), CATS[c]) for a, b, c in re.findall(r"\{0x([0-9a-f]+), 0x([0-9a-f]+), (\w+)\}", body)]
assert len(cat_ranges) == n

ranges = {}
for name in ["unicode_alphabetic", "unicode_lowercase", "unicode_uppercase", "unicode_case_ignorable",
             "unicode_white_space", "unicode_hex_digit", "unicode_join_control"]:
    n, body = table(name)
    r = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9a-f]+), 0x([0-9a-f]+)\}", body)]
    assert len(r) == n, name
    ranges[name] = r

with open(out_path, "w") as f:
    f.write("// @generated by tests/gen/gen_unicode_tables.py from PostgreSQL 17\n")
    f.write("// src/include/common/unicode_case_table.h and unicode_category_table.h\n")
    f.write("// (Unicode 15.1). Portions Copyright (c) 1996-2024, PostgreSQL Global\n")
    f.write("// Development Group; PostgreSQL License. Do not edit.\n\n")
    f.write("/// Simple case mappings for code points >= 0x80: (code, lower, title, upper).\n")
    f.write(f"pub(crate) static CASE_MAP: [(u32, u32, u32, u32); {len(sparse)}] = [\n")
    for c in sparse:
        f.write("    (0x%x, 0x%x, 0x%x, 0x%x),\n" % c)
    f.write("];\n\n")
    f.write("/// (category, property bits) for ASCII code points.\n")
    f.write("pub(crate) static ASCII_PROPS: [(u8, u8); 128] = [\n")
    for c in ascii:
        f.write("    (%d, %d),\n" % c)
    f.write("];\n\n")
    f.write("/// General category ranges: (first, last, category).\n")
    f.write(f"pub(crate) static CATEGORIES: [(u32, u32, u8); {len(cat_ranges)}] = [\n")
    for c in cat_ranges:
        f.write("    (0x%x, 0x%x, %d),\n" % c)
    f.write("];\n")
    for name, r in ranges.items():
        rust = name.replace("unicode_", "").upper()
        f.write(f"\npub(crate) static {rust}: [(u32, u32); {len(r)}] = [\n")
        for a, b in r:
            f.write("    (0x%x, 0x%x),\n" % (a, b))
        f.write("];\n")
print("ok", len(sparse), len(cat_ranges), {k: len(v) for k, v in ranges.items()})
