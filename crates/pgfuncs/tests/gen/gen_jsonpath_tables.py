"""Generate src/json/path/tables.rs: the scanner and parser tables of
PostgreSQL 17's jsonpath lexer/grammar.

PostgreSQL builds the jsonpath scanner with flex and the parser with bison.
To reproduce their behaviour exactly (longest-match tokenization, rule
priorities, the token at which a syntax error is detected, the order in which
semantic actions run), pgfuncs ports the generated DFA and LALR tables and
re-implements the flex/bison driver loops in Rust (src/json/path/scan.rs and
src/json/path/gram.rs). Table compression does not change behaviour, so the
default flex table format is used.

Inputs (from the PostgreSQL REL_17_STABLE tree):
  src/backend/utils/adt/jsonpath_gram.y
  src/backend/utils/adt/jsonpath_scan.l

Usage: BISON=... FLEX=... python3 gen_jsonpath_tables.py <dir-with-.y-and-.l> <output.rs>
(tested with bison 3.8.2 and flex 2.6.4)
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

src_dir, out_path = sys.argv[1], sys.argv[2]
bison = os.environ.get("BISON", "bison")
flex = os.environ.get("FLEX", "flex")

tmp = tempfile.mkdtemp()
try:
    shutil.copy(os.path.join(src_dir, "jsonpath_gram.y"), tmp)
    shutil.copy(os.path.join(src_dir, "jsonpath_scan.l"), tmp)
    subprocess.run([bison, "-d", "-o", "gram.c", "jsonpath_gram.y"], cwd=tmp, check=True,
                   stderr=subprocess.DEVNULL)
    subprocess.run([flex, "-o", "scan.c", "jsonpath_scan.l"], cwd=tmp, check=True)
    gram = open(os.path.join(tmp, "gram.c")).read()
    gram_h = open(os.path.join(tmp, "gram.h")).read()
    scan = open(os.path.join(tmp, "scan.c")).read()
    bison_ver = subprocess.run([bison, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    flex_ver = subprocess.run([flex, "--version"], capture_output=True, text=True).stdout.strip()
finally:
    shutil.rmtree(tmp)


def array(src, name):
    m = re.search(r"static const [\w ]+ " + name + r"\[(\d*)\] =\s*\{(.*?)\}\s*;", src, re.S)
    assert m, name
    vals = [int(x) for x in m.group(2).replace("\n", " ").split(",") if x.strip()]
    if m.group(1):
        assert len(vals) == int(m.group(1)), name
    return vals


def define(src, name):
    m = re.search(r"#define " + name + r"\s+\(?(-?\d+)\)?", src)
    assert m, name
    return int(m.group(1))


# ---------------------------------------------------------------- flex
accept = array(scan, "yy_accept")
ec = array(scan, "yy_ec")
meta = array(scan, "yy_meta")
base = array(scan, "yy_base")
dflt = array(scan, "yy_def")
nxt = array(scan, "yy_nxt")
chk = array(scan, "yy_chk")
jam = int(re.search(r"while \( yy_current_state != (\d+) \);", scan).group(1))
threshold = int(re.search(r"if \( yy_current_state >= (\d+) \)\s*yy_c = yy_meta\[yy_c\];", scan).group(1))
num_rules = define(scan, "YY_NUM_RULES")
eob = define(scan, "YY_END_OF_BUFFER")
starts = {n: int(v) for n, v in re.findall(r"#define (INITIAL|xq|xnq|xvq|xc) (\d+)", scan)}
assert starts == {"INITIAL": 0, "xq": 1, "xnq": 2, "xvq": 3, "xc": 4}, starts
# rule number -> source line of the rule in jsonpath_scan.l
rule_lines = {int(n): int(l) for n, l in re.findall(r"case (\d+):\n(?:/\*.*\*/\n)?YY_RULE_SETUP\n#line (\d+)", scan)}
assert sorted(rule_lines) == list(range(1, num_rules + 1)), rule_lines
lfile = open(os.path.join(src_dir, "jsonpath_scan.l")).read().split("\n")

# ---------------------------------------------------------------- bison
consts = {n: define(gram, n) for n in ["YYFINAL", "YYLAST", "YYNTOKENS", "YYNNTS", "YYNRULES", "YYNSTATES",
                                       "YYMAXUTOK", "YYPACT_NINF", "YYTABLE_NINF"]}
assert re.search(r"#define yytable_value_is_error\(Yyn\) \\\n\s*0", gram)
translate = array(gram, "yytranslate")
pact = array(gram, "yypact")
defact = array(gram, "yydefact")
pgoto = array(gram, "yypgoto")
defgoto = array(gram, "yydefgoto")
table = array(gram, "yytable")
check = array(gram, "yycheck")
r1 = array(gram, "yyr1")
r2 = array(gram, "yyr2")
tokens = re.findall(r"\n\s+(\w+) = (\d+),?\s+/\*", gram_h)
tokens = [(n, int(v)) for n, v in tokens if n not in ("YYEMPTY", "YYEOF", "YYerror", "YYUNDEF")]


def rust_array(name, typ, vals, per_line=16):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    return f"pub(super) static {name}: [{typ}; {len(vals)}] = [\n" + "\n".join(lines) + "\n];\n"


out = []
out.append(f"""// @generated by tests/gen/gen_jsonpath_tables.py from PostgreSQL 17
// src/backend/utils/adt/jsonpath_scan.l ({flex_ver}) and jsonpath_gram.y
// ({bison_ver}). Portions Copyright (c) 2019-2024, PostgreSQL Global
// Development Group; PostgreSQL License. Do not edit.

#![allow(dead_code)]

// ------------------------------------------------------------------ flex

/// DFA state at which the scanner jams (no further transition).
pub(super) const YY_JAMSTATE: i16 = {jam};
/// States >= this are template states: use `YY_META` for the class.
pub(super) const YY_TEMPLATE_STATES: i16 = {threshold};
/// Action number of the end-of-buffer pseudo rule; the EOF action of start
/// condition `s` is `YY_END_OF_BUFFER + 1 + s`.
pub(super) const YY_END_OF_BUFFER: i16 = {eob};

// Rule numbers (YY_ACCEPT values) and their jsonpath_scan.l source lines:
""")
for n in range(1, num_rules + 1):
    line = rule_lines[n]
    text = lfile[line - 1].strip().split("\t")[0].strip()
    out.append(f"//   {n:2}: line {line:3}  {text}\n")
out.append("\n")
out.append(rust_array("YY_ACCEPT", "i16", accept))
out.append(rust_array("YY_EC", "u8", ec))
out.append(rust_array("YY_META", "u8", meta))
out.append(rust_array("YY_BASE", "i16", base))
out.append(rust_array("YY_DEF", "i16", dflt))
out.append(rust_array("YY_NXT", "i16", nxt))
out.append(rust_array("YY_CHK", "i16", chk))
out.append("\n// ----------------------------------------------------------------- bison\n\n")
for n, v in consts.items():
    out.append(f"pub(super) const {n}: i32 = {v};\n")
out.append("\n// Token codes returned by the scanner (enum yytokentype).\n")
for n, v in tokens:
    out.append(f"pub(super) const {n}: i32 = {v};\n")
out.append("\n")
out.append(rust_array("YYTRANSLATE", "u8", translate))
out.append(rust_array("YYPACT", "i16", pact))
out.append(rust_array("YYDEFACT", "u8", defact))
out.append(rust_array("YYPGOTO", "i16", pgoto))
out.append(rust_array("YYDEFGOTO", "u8", defgoto))
out.append(rust_array("YYTABLE", "i16", table))
out.append(rust_array("YYCHECK", "i16", check))
out.append(rust_array("YYR1", "u8", r1))
out.append(rust_array("YYR2", "u8", r2))

with open(out_path, "w") as f:
    f.write("".join(out))
print(f"wrote {out_path}")
