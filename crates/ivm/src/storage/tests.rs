// the harness

struct Harness {
    rng: Rng,
    _tmp: TempDir,
    dir: PathBuf,
    opts: EnvOptions,
    env: Option<Env>,
    model: Model,
    gsn: Gsn,
    retention: u64,
    /// Highest frontier set so far: reads at or after it are exact.
    frontier: Gsn,
    ckpt: Ckpt,
    /// Operations since the last checkpoint (the "input log").
    since: Vec<Op>,
    checkpoints: u64,
    events: BTreeMap<&'static str, u64>,
    /// Kind-2 nodes may be present (the case started in legacy format).
    legacy: bool,
    /// Forks with the model, frontier and GSN as of when they were taken.
    forks: Vec<(Env, Model, Gsn, Gsn)>,
    /// A tree being filled in a fork (left alone here until adopted).
    adopting: Option<TreeId>,
}

impl Harness {
    fn new(setup: &Setup, name: &str) -> Harness {
        let tmp = TempDir::new(name);
        let dir = tmp.path().join("store");
        let (mut env, rec) = Env::open(&dir, setup.opts.clone()).unwrap();
        assert!(rec.is_none());
        // until the first reopen, which uses the current formats
        env.legacy_format = setup.legacy;
        let ckpt = Ckpt { durable: false, gsn: 0, app: vec![], model: Model::new(), frontier: 0 };
        Harness {
            rng: Rng::new(0),
            _tmp: tmp,
            dir,
            opts: setup.opts.clone(),
            env: Some(env),
            model: Model::new(),
            gsn: 0,
            retention: setup.retention,
            frontier: 0,
            ckpt,
            since: vec![],
            checkpoints: 0,
            events: BTreeMap::new(),
            legacy: setup.legacy,
            forks: Vec::new(),
            adopting: None,
        }
    }

    fn env(&mut self) -> &mut Env {
        self.env.as_mut().unwrap()
    }

    fn event(&mut self, name: &'static str) {
        *self.events.entry(name).or_default() += 1;
    }

    fn op(&mut self, op: Op) {
        apply_op(self.env.as_mut().unwrap(), &mut self.model, &mut self.frontier, &op);
        self.since.push(op);
    }

    fn create_tree(&mut self) {
        let id = self.env().next_tree_id();
        let kind = *self.rng.pick(&KINDS);
        let universe = *self.rng.pick(&[30, 200, 3000]);
        self.op(Op::Create { id, kind, universe });
    }

    fn step(&mut self) {
        if self.model.is_empty() {
            self.create_tree();
        }
        self.gsn += if self.rng.chance(10) { self.rng.range(2, 5) as u64 } else { 1 };
        let ids: Vec<TreeId> = self.model.keys().copied().filter(|id| Some(*id) != self.adopting).collect();
        if ids.is_empty() {
            return;
        }
        let n = 1 + self.rng.index(ids.len().min(3));
        for _ in 0..n {
            let id = *self.rng.pick(&ids);
            let ups = gen_batch(&mut self.rng, &self.model[&id]);
            self.op(Op::Apply { tree: id, ups, gsn: self.gsn });
        }
        let f = self.gsn.saturating_sub(self.retention);
        if f > self.frontier {
            self.op(Op::Frontier(f));
        }
    }

    /// Updates while a background checkpoint is written or a fork is
    /// filled: steps, tree creation and drops, GC, forks.
    fn meanwhile(&mut self) {
        for _ in 0..self.rng.range(0, 6) {
            match self.rng.below(11) {
                0 => self.create_tree(),
                1 if self.model.len() > 2 => {
                    let ids: Vec<TreeId> = self.model.keys().copied().filter(|id| Some(*id) != self.adopting).collect();
                    let id = *self.rng.pick(&ids);
                    self.op(Op::Drop(id));
                }
                2 => self.maintain(),
                3 => self.fork(),
                4 => self.write_back(),
                _ => self.step(),
            }
        }
    }

    /// Write dirty nodes early (`Env::write_back`), all or some (while a
    /// checkpoint is written, not the nodes frozen in it, nor their
    /// ancestors).
    fn write_back(&mut self) {
        let dirty = self.env().dirty_bytes() as u64;
        let target = if self.rng.chance(50) { 0 } else { self.rng.below(dirty + 1) as usize };
        let left = self.env().write_back(target).unwrap();
        if self.env().frozen_at.is_none() {
            assert!(left <= target, "write_back to {target} left {left} dirty bytes");
        } else if left < dirty as usize {
            self.event("early writes while a checkpoint is written");
        }
    }

    fn fork(&mut self) {
        self.event("fork");
        let f = self.env().fork().unwrap_or_else(|e| panic!("fork: {e}"));
        if self.forks.len() >= 2 {
            self.forks.remove(0);
        }
        self.forks.push((f, self.model.clone(), self.frontier, self.gsn));
    }

    /// A fork still reads every tree as of when it was taken, also after
    /// updates of its own (which do not show in the environment).
    fn check_fork(&mut self) {
        if self.forks.is_empty() {
            return;
        }
        self.event("check fork");
        let i = self.rng.index(self.forks.len());
        let (mut f, mut model, mut frontier, now) = self.forks.remove(i);
        let legacy = self.legacy;
        // (its segment accounting too: what it writes counts as its trees')
        let verify = |f: &mut Env, rng: &mut Rng, model: &Model, frontier: Gsn, now: Gsn| {
            assert_eq!(f.tree_ids(), model.keys().copied().collect::<Vec<_>>(), "tree set of a fork");
            for (id, m) in model {
                verify_tree(f, rng, *id, m, frontier, now);
            }
            check_structure(f, legacy, None);
        };
        verify(&mut f, &mut self.rng, &model, frontier, now);
        let ids: Vec<TreeId> = model.keys().copied().collect();
        if !ids.is_empty() {
            for k in 0..self.rng.range(1, 4) {
                let id = *self.rng.pick(&ids);
                let ups = gen_batch(&mut self.rng, &model[&id]);
                apply_op(&mut f, &mut model, &mut frontier, &Op::Apply { tree: id, ups, gsn: now + 1 + k as u64 });
            }
            verify(&mut f, &mut self.rng, &model, frontier, now + 3);
        }
        if f.trees.values().any(|t| t.seg_live.keys().any(|s| f.segs.pinned(*s))) {
            self.event("fork wrote nodes");
        }
        drop(f);
        self.verify();
    }

    /// Create a tree here, fill it in a fork while the environment goes on,
    /// and adopt it.
    fn adopt(&mut self) {
        self.event("adopt");
        let id = self.env().next_tree_id();
        let kind = *self.rng.pick(&KINDS);
        let universe = *self.rng.pick(&[30, 200, 3000]);
        self.op(Op::Create { id, kind, universe });
        let mut m = self.model[&id].clone();
        let mut f = self.env().fork().unwrap();
        let at = self.gsn;
        self.adopting = Some(id);
        self.meanwhile();
        self.adopting = None;
        // (the model is never compacted: the fork's frontier does not matter)
        let mut ops = Vec::new();
        for k in 0..self.rng.range(1, 8) {
            let ups = gen_batch(&mut self.rng, &m);
            let op = Op::Apply { tree: id, ups, gsn: at + 1 + k as u64 };
            let mut single = Model::from([(id, m)]);
            let mut fr = 0;
            apply_op(&mut f, &mut single, &mut fr, &op);
            m = single.remove(&id).unwrap();
            ops.push(op);
        }
        if !f.trees[&id].seg_live.is_empty() {
            self.event("adopt: a tree the fork wrote nodes of");
        }
        self.env().adopt_trees(&mut f, &[id]).unwrap();
        drop(f);
        self.model.insert(id, m);
        // replayed after a crash as if applied here
        self.since.extend(ops);
        self.gsn = self.gsn.max(at + 8);
        self.verify();
    }

    /// A checkpoint written in the background: begun, written and finished
    /// with updates in between, or interrupted by a crash.
    fn async_checkpoint(&mut self) {
        self.checkpoints += 1;
        let (gsn, app) = (self.gsn, format!("checkpoint {} at {}", self.checkpoints, self.gsn).into_bytes());
        let job = self.env().begin_checkpoint(gsn).unwrap();
        assert!(self.env().begin_checkpoint(gsn).is_err(), "a second checkpoint while one is in progress");
        let frozen = Ckpt { durable: true, gsn, app: app.clone(), model: self.model.clone(), frontier: self.frontier };
        let since_freeze = self.since.len();
        self.meanwhile();
        if self.rng.chance(10) {
            self.event("crash: before background checkpoint written");
            drop(job);
            self.env = None;
            self.forks.clear();
            let ckpt = self.ckpt.clone();
            return self.recover(ckpt);
        }
        let done = job.run(&app).unwrap();
        self.meanwhile();
        self.since.drain(..since_freeze);
        if self.rng.chance(10) {
            self.event("crash: before background checkpoint finished");
            drop(done);
            self.env = None;
            self.forks.clear();
            return self.recover(frozen);
        }
        self.event("background checkpoint");
        self.env().finish_checkpoint(done).unwrap();
        self.ckpt = frozen;
        check_segment_files(self.env.as_mut().unwrap(), false);
        self.verify();
    }

    fn checkpoint(&mut self) {
        if self.rng.chance(30) {
            self.maintain();
        }
        self.checkpoint_now();
    }

    /// A maintenance pass with random budgets (sometimes none at all).
    fn maintain(&mut self) {
        let mut budget = || match self.rng.below(4) {
            0 => 0,
            1 => u64::MAX,
            _ => self.rng.range(1, 20_000) as u64,
        };
        let b = MaintBudget { compact: budget(), gc: budget(), memory: usize::MAX };
        let st = self.env().maintain_with(b).unwrap();
        if st.merged > 0 {
            self.event("merges");
        }
        if st.compacted > 0 {
            self.event("compactions");
        }
    }

    fn checkpoint_now(&mut self) {
        self.checkpoints += 1;
        let (gsn, app) = (self.gsn, format!("checkpoint {} at {}", self.checkpoints, self.gsn).into_bytes());
        self.env().checkpoint(gsn, &app).unwrap();
        self.ckpt = Ckpt { durable: true, gsn, app, model: self.model.clone(), frontier: self.frontier };
        self.since.clear();
        check_segment_files(self.env.as_mut().unwrap(), true);
    }

    /// One maintenance pass without limits must compact every leaf whose
    /// compaction is due and evacuate every sparse segment completely
    /// (rounds need not converge: with segments not much larger than nodes,
    /// moving a leaf rewrites its path, which can make the previous round's
    /// segments sparse again).
    fn gc_round(&mut self) {
        // flushing dirty nodes turns their previous images into garbage
        self.checkpoint_now();
        let env = self.env.as_ref().unwrap();
        let active = env.segs.active_id();
        let sparse: Vec<u32> =
            env.seg_live.iter().filter(|(id, (_, live))| **id != active && *live > 0 && live * 2 < env.seg_live[id].0).map(|(id, _)| *id).collect();
        let st = self.env().maintain_with(MaintBudget::UNLIMITED).unwrap();
        assert_eq!(st.victims, sparse, "segments chosen for evacuation without a budget");
        if !sparse.is_empty() {
            assert!(st.relocated > 0, "GC found no live node in sparse segments {sparse:?}");
        }
        let frontier = self.frontier;
        let legacy = self.legacy;
        check_structure(self.env(), legacy, Some(frontier));
        self.checkpoint_now();
        let env = self.env.as_ref().unwrap();
        for v in sparse {
            assert!(!env.seg_live.contains_key(&v), "GC did not evacuate segment {v}: {:?}", env.seg_live.get(&v));
        }
    }

    fn verify(&mut self) {
        let (frontier, now) = (self.frontier, self.gsn);
        verify_all(self.env.as_mut().unwrap(), &mut self.rng, &self.model, frontier, now, self.legacy);
    }

    fn reopen(&mut self) {
        self.checkpoint();
        self.env = None;
        self.forks.clear();
        let ckpt = self.ckpt.clone();
        self.recover(ckpt);
    }

    /// Reopen after a simulated crash (the environment is already dropped and
    /// the files are as the crash left them), expecting `expect` to be the
    /// recovered checkpoint, then replay the operations since it.
    fn recover(&mut self, expect: Ckpt) {
        let (env, rec) = Env::open(&self.dir, self.opts.clone()).unwrap();
        self.env = Some(env);
        match rec {
            None => assert!(!expect.durable, "checkpoint at gsn {} lost", expect.gsn),
            Some(r) => {
                assert!(expect.durable, "recovered a checkpoint at gsn {} that never completed", r.gsn);
                assert_eq!((r.gsn, &r.app), (expect.gsn, &expect.app), "recovered checkpoint");
            }
        }
        let env = self.env.as_mut().unwrap();
        assert_eq!(env.unattached_trees(), expect.model.keys().copied().collect::<Vec<_>>(), "recovered trees");
        for (id, m) in &expect.model {
            env.attach_tree(*id, summarizer(m.kind)).unwrap();
        }
        env.set_frontier(expect.frontier);
        check_segment_files(env, false);
        verify_all(env, &mut self.rng, &expect.model, expect.frontier, expect.gsn, self.legacy);
        // replay the log since the checkpoint
        let mut model = expect.model.clone();
        let mut frontier = expect.frontier;
        for op in &self.since {
            apply_op(env, &mut model, &mut frontier, op);
        }
        assert!(model == self.model, "replay diverged from the state before the crash");
        assert_eq!(frontier, self.frontier);
        self.ckpt = expect;
        self.verify();
    }

    fn crash(&mut self) {
        let variant = self.rng.below(6);
        if variant >= 4 && self.ckpt.durable {
            return self.crash_in_checkpoint(variant == 5);
        }
        self.forks.clear();
        if self.rng.chance(50) {
            self.crash_after_early_writes();
        }
        let env = self.env.take().unwrap();
        let active = segment::segment_path(&self.dir, env.segs.active_id());
        let next = segment::segment_path(&self.dir, env.segs.active_id() + 1);
        drop(env);
        let garbage: Vec<u8> = (0..self.rng.range(1, 300)).map(|_| self.rng.next() as u8).collect();
        let append = |path: &Path, bytes: &[u8]| {
            let mut data = std::fs::read(path).unwrap_or_default();
            data.extend_from_slice(bytes);
            std::fs::write(path, data).unwrap();
        };
        match variant {
            1 => {
                self.event("crash: torn manifest");
                let tail = match self.rng.below(3) {
                    0 => garbage,
                    // a frame header promising more bytes than follow
                    1 => [&(garbage.len() as u32 + 10).to_le_bytes()[..], &[0; 4], &garbage].concat(),
                    // a complete frame with a bad checksum
                    _ => [&(garbage.len() as u32).to_le_bytes()[..], &[1, 2, 3, 4], &garbage].concat(),
                };
                append(&self.dir.join("MANIFEST"), &tail);
                if !self.ckpt.durable {
                    // No checkpoint was ever committed, so the manifest holds
                    // nothing but the torn record: a manifest with contents
                    // and no valid record is refused, every file left as it
                    // was. The documented remedy for a crash during the first
                    // checkpoint is to remove the store and rebuild it from
                    // the input log, which recover() below does.
                    self.event("crash: torn first manifest record");
                    let before = std::fs::read(self.dir.join("MANIFEST")).unwrap();
                    let err = Env::open(&self.dir, self.opts.clone()).err().expect("a manifest without a valid record is refused");
                    assert_eq!(err.code, crate::error::codes::DATA_CORRUPTED, "{}", err.message);
                    assert_eq!(std::fs::read(self.dir.join("MANIFEST")).unwrap(), before, "the refused manifest was modified");
                    std::fs::remove_dir_all(&self.dir).unwrap();
                }
            }
            2 => {
                self.event("crash: segment garbage");
                append(&active, &garbage);
            }
            3 => {
                self.event("crash: stray segment");
                append(&next, &garbage);
            }
            _ => self.event("crash"),
        }
        let ckpt = self.ckpt.clone();
        self.recover(ckpt);
    }

    /// Before a crash: write dirty nodes early (all or some, as memory
    /// pressure does) and hand them to the OS, perhaps tearing the last of
    /// them. None of it is part of the last checkpoint, which the crash
    /// must recover.
    fn crash_after_early_writes(&mut self) {
        self.event("crash: after early writes");
        let env = self.env.as_mut().unwrap();
        env.segs.write_buffer().unwrap();
        let (seg, len) = (env.segs.active_id(), env.segs.active_len());
        let target = if self.rng.chance(50) { 0 } else { self.rng.below(env.dirty_bytes() as u64 + 1) as usize };
        let env = self.env.as_mut().unwrap();
        env.write_back(target).unwrap();
        env.segs.write_buffer().unwrap();
        let (seg2, len2) = (env.segs.active_id(), env.segs.active_len());
        if self.rng.chance(50) {
            // torn: the newest segment ends somewhere among the new frames
            let from = if seg2 == seg { len } else { 0 };
            if len2 > from {
                self.event("crash: torn early writes");
                let cut = from + self.rng.below(len2 - from);
                std::fs::OpenOptions::new().write(true).open(segment::segment_path(&self.dir, seg2)).unwrap().set_len(cut).unwrap();
            }
        }
    }

    /// Crash during a checkpoint: before its manifest record is complete
    /// (the previous checkpoint must be recovered), or after the record but
    /// before freed segments are deleted (the new one must be recovered).
    fn crash_in_checkpoint(&mut self, record_written: bool) {
        let files = |dir: &Path| -> BTreeMap<String, Vec<u8>> {
            std::fs::read_dir(dir)
                .unwrap()
                .map(|e| {
                    let e = e.unwrap();
                    (e.file_name().to_string_lossy().into_owned(), std::fs::read(e.path()).unwrap())
                })
                .collect()
        };
        let before = files(&self.dir);
        let old_active = format!("seg-{:08}.dat", self.env().segs.active_id());
        self.checkpoints += 1;
        let (gsn, app) = (self.gsn, format!("checkpoint {} at {}", self.checkpoints, self.gsn).into_bytes());
        self.env().checkpoint(gsn, &app).unwrap();
        let after = files(&self.dir);
        self.env = None;
        self.forks.clear();
        let mut image: BTreeMap<String, Vec<u8>> = BTreeMap::new();
        for (name, data) in &after {
            if name.starts_with("seg-") {
                if let Some(old) = before.get(name) {
                    assert!(data.starts_with(old), "segment {name} changed other than by appending");
                }
                image.insert(name.clone(), data.clone());
            }
        }
        for (name, data) in &before {
            if name.starts_with("seg-") {
                // freed by the checkpoint, but the crash came first
                image.entry(name.clone()).or_insert_with(|| data.clone());
            }
        }
        let old_manifest = before.get("MANIFEST").cloned().unwrap_or_default();
        let new_manifest = after["MANIFEST"].clone();
        if record_written {
            self.event("crash: after checkpoint record");
            image.insert("MANIFEST".into(), new_manifest);
            self.ckpt = Ckpt { durable: true, gsn, app, model: self.model.clone(), frontier: self.frontier };
            self.since.clear();
        } else {
            self.event("crash: inside checkpoint");
            // the new nodes may be partly written...
            for (name, data) in image.iter_mut() {
                let old_len = before.get(name).map(|d| d.len()).unwrap_or(0);
                if (name == &old_active || !before.contains_key(name)) && data.len() > old_len && self.rng.chance(50) {
                    data.truncate(old_len + self.rng.index(data.len() - old_len));
                }
            }
            // ...and so may the manifest record
            let mut m = old_manifest.clone();
            if new_manifest.len() > m.len() && new_manifest.starts_with(&m) && self.rng.chance(60) {
                let extra = &new_manifest[m.len()..];
                m.extend_from_slice(&extra[..self.rng.index(extra.len())]);
            }
            image.insert("MANIFEST".into(), m);
        }
        for name in after.keys() {
            std::fs::remove_file(self.dir.join(name)).unwrap();
        }
        for (name, data) in &image {
            std::fs::write(self.dir.join(name), data).unwrap();
        }
        let ckpt = self.ckpt.clone();
        self.recover(ckpt);
    }

    /// Drop every tree: all space must be reclaimed.
    fn finish(&mut self) {
        // (forks pin the segments they wrote to)
        self.forks.clear();
        for _ in 0..3 {
            self.gc_round();
        }
        for id in self.model.keys().copied().collect::<Vec<_>>() {
            self.op(Op::Drop(id));
        }
        self.checkpoint();
        let env = self.env.as_ref().unwrap();
        let active = env.segs.active_id();
        assert_eq!(env.stats().segments.iter().map(|s| s.2).sum::<u64>(), 0, "live bytes after dropping every tree");
        assert!(env.seg_live.keys().all(|s| *s == active), "segments left after dropping every tree: {:?}", env.seg_live);
        self.verify();
    }
}

/// Engine-independent parameters of a case.
#[derive(Clone, Debug)]
struct Setup {
    opts: EnvOptions,
    retention: u64,
    /// Start with the formats of earlier versions.
    legacy: bool,
}

fn arb_setup() -> impl Strategy<Value = Setup> {
    // shrinking prefers the first choice of each: no eviction, large nodes
    (
        select(vec![64 << 20, 256 << 10, 32 << 10, 8 << 10, 2 << 10]),
        select(vec![16 << 10, 2048, 512, 128]),
        select(vec![16 << 10, 4096, 512, 128]),
        select(vec![1 << 20, 64 << 10, 8 << 10, 2 << 10]),
        select(vec![10, 3, 1, 0, 50]),
        select(vec![false, true]),
    )
        .prop_map(|(cache_bytes, leaf_bytes, internal_bytes, segment_bytes, retention, legacy)| Setup {
            opts: EnvOptions { cache_bytes, leaf_bytes, internal_bytes, segment_bytes },
            retention,
            legacy,
        })
}

#[derive(Clone, Copy, Debug)]
enum Action {
    /// Updates at the next GSN to up to three trees.
    Step,
    CreateTree,
    DropTree,
    /// A maintenance pass (sometimes) and a checkpoint.
    Checkpoint,
    /// A maintenance pass with random budgets.
    Gc,
    /// Write dirty nodes early (`Env::write_back`).
    WriteBack,
    /// A maintenance pass without limits, between checkpoints.
    GcRound,
    /// Checkpoint, close and reopen.
    Reopen,
    Crash,
    Verify,
    /// The buffer pool's target changes (`Env::set_cache_bytes`, as the
    /// memory budget rebalances it); the next access evicts down to it.
    Cache,
    AsyncCheckpoint,
    Fork,
    CheckFork,
    Adopt,
}

/// An action with the seed of the random choices it makes.
fn arb_action() -> impl Strategy<Value = (Action, u64)> {
    use Action::*;
    let kind = prop_oneof![
        63 => Just(Step),
        4 => Just(CreateTree),
        2 => Just(DropTree),
        9 => Just(Checkpoint),
        2 => Just(Gc),
        2 => Just(WriteBack),
        1 => Just(GcRound),
        2 => Just(Reopen),
        5 => Just(Crash),
        4 => Just(Verify),
        2 => Just(Cache),
        6 => Just(AsyncCheckpoint),
        3 => Just(Fork),
        3 => Just(CheckFork),
        2 => Just(Adopt),
    ];
    (kind, any::<u64>())
}

fn run(setup: &Setup, actions: &[(Action, u64)], name: &str) {
    let mut h = Harness::new(setup, name);
    for (action, seed) in actions {
        h.rng = Rng::new(*seed);
        match action {
            Action::Step => h.step(),
            Action::CreateTree => h.create_tree(),
            Action::DropTree => {
                if h.model.len() > 1 {
                    let id = *h.rng.pick(&h.model.keys().copied().collect::<Vec<_>>());
                    h.op(Op::Drop(id));
                }
            }
            Action::Checkpoint => {
                h.event("checkpoint");
                h.checkpoint()
            }
            Action::Gc => h.maintain(),
            Action::WriteBack => h.write_back(),
            Action::GcRound => h.gc_round(),
            Action::Reopen => {
                h.event("reopen");
                h.reopen()
            }
            Action::Crash => h.crash(),
            Action::Verify => h.verify(),
            Action::Cache => {
                h.event("cache target");
                let bytes = *h.rng.pick(&[64 << 20, 256 << 10, 32 << 10, 8 << 10, 2 << 10]);
                h.env().set_cache_bytes(bytes);
            }
            Action::AsyncCheckpoint => h.async_checkpoint(),
            Action::Fork => h.fork(),
            Action::CheckFork => h.check_fork(),
            Action::Adopt => h.adopt(),
        }
        let (frontier, now) = (h.frontier, h.gsn);
        verify_points(h.env.as_mut().unwrap(), &mut h.rng, &h.model, frontier, now);
    }
    h.verify();
    h.finish();
    if std::env::var("IVM_MODEL_EVENTS").is_ok() {
        eprintln!("EVENTS {:?}", h.events);
    }
}

