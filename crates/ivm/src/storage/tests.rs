/// `leaf_compaction` agrees with compacting each entry by brute force: the
/// first frontier that changes anything, and the first at which a quarter
/// of the leaf's size goes.
#[test]
fn leaf_compaction_matches_brute_force() {
    let mut rng = Rng::new(7);
    for _ in 0..2000 {
        let mut entries = Vec::new();
        for i in 0..rng.range(1, 12) {
            let mut h = History::default();
            let mut g = 0;
            for _ in 0..rng.range(1, 5) {
                g += rng.range(1, 6) as Gsn;
                let w = if rng.chance(50) { -1 } else { 1 + rng.below(2) as i64 };
                h.0.push((g, w));
            }
            let key = format!("k{i:03}").repeat(rng.range(1, 4) as usize).into_bytes().into_boxed_slice();
            entries.push(LeafEntry { key, hist: h });
        }
        let size = Node::Leaf(entries.clone()).byte_size();
        let after = |f: Gsn| -> usize {
            8 + entries
                .iter()
                .map(|e| {
                    let mut h = e.hist.clone();
                    h.compact(f);
                    if h.is_empty() { 0 } else { entry_size(&LeafEntry { key: e.key.clone(), hist: h }) }
                })
                .sum::<usize>()
        };
        let first = (0..40).find(|f| after(*f) != size).unwrap_or(Gsn::MAX);
        let due = (0..40).find(|f| 4 * (size - after(*f)) >= size).unwrap_or(Gsn::MAX);
        assert_eq!(leaf_compaction(&entries), (first, due), "{entries:?}");
    }
}

/// Leaves, internal nodes, entries and bytes of leaves of a tree.
fn shape(env: &mut Env, tree: TreeId) -> (usize, usize, usize, usize) {
    fn rec(env: &mut Env, id: u32, acc: &mut (usize, usize, usize, usize)) {
        match env.node(id) {
            Node::Leaf(entries) => {
                acc.0 += 1;
                acc.2 += entries.len();
                acc.3 += env.slot(id).bytes;
            }
            Node::Internal(ch) => {
                acc.1 += 1;
                for i in 0..ch.len() {
                    let c = env.load_child(id, i).unwrap();
                    rec(env, c, acc);
                }
            }
        }
    }
    let mut acc = (0, 0, 0, 0);
    if let Some(root) = env.root_slot(tree).unwrap() {
        rec(env, root, &mut acc);
    }
    acc
}

fn key8(i: u64, pad: usize) -> Vec<u8> {
    let mut k = i.to_be_bytes().to_vec();
    k.resize(8 + pad, b'p');
    k
}

/// Entries visited before the first live one.
fn dead_prefix(env: &mut Env, tree: TreeId) -> usize {
    let mut n = 0;
    env.for_each(tree, Bound::Unbounded, Bound::Unbounded, &mut |_, h| {
        n += 1;
        Ok(h.total() == 0)
    })
    .unwrap();
    n - 1
}

/// A queue (insert at the tail, delete at the head): leaves at the head are
/// never written again, yet the dead entries go once the frontier passes
/// them. (Before the maintenance pass the tree kept every row ever inserted.)
#[test]
fn queue_keeps_only_the_retention_window() {
    let tmp = TempDir::new("storage-queue");
    let (mut env, _) = Env::open(tmp.path(), EnvOptions::default()).unwrap();
    let t = env.create_tree(Arc::new(CountSummarizer));
    let (window, retention, every, n) = (100u64, 200u64, 100u64, 20_000u64);
    for g in 1..=n {
        env.set_frontier(g.saturating_sub(retention));
        let mut ups = vec![(key8(g, 40), 1)];
        if g > window {
            ups.push((key8(g - window, 40), -1));
        }
        env.apply(t, &mut ups, g).unwrap();
        if g % every == 0 {
            env.maintain().unwrap();
            env.checkpoint(g, b"").unwrap();
        }
    }
    let (_, _, entries, _) = shape(&mut env, t);
    // live rows, retractions within the retention window or since the last
    // pass, and less than a quarter of the leaf at the frontier
    let bound = (window + retention + every + 100) as usize;
    assert!(entries <= bound, "{entries} entries for a queue of {window} (bound {bound})");
    let dead = dead_prefix(&mut env, t);
    assert!(dead <= bound - window as usize, "{dead} dead entries before the first live one");
    let live: u64 = env.stats().segments.iter().map(|s| s.2).sum();
    assert!(live < 64 << 10, "{live} live bytes for a queue of {window} rows");
}

/// Deleting 99% of a table: once the frontier passes the deletes, a pass
/// compacts every leaf and merges the remains. (Before, the deletes split
/// the leaves (each entry grew by a history element) and nothing merged
/// them again: about three times as many leaves as before the deletes.)
#[test]
fn mass_delete_is_compacted_and_merged() {
    let tmp = TempDir::new("storage-mass-delete");
    let (mut env, _) = Env::open(tmp.path(), EnvOptions::default()).unwrap();
    let t = env.create_tree(Arc::new(CountSummarizer));
    let n = 200_000u64;
    let mut g = 0;
    for c in (0..n).step_by(50_000) {
        g += 1;
        env.apply(t, &mut (c..c + 50_000).map(|i| (key8(i, 0), 1)).collect(), g).unwrap();
    }
    env.checkpoint(g, b"").unwrap();
    let (full, _, _, _) = shape(&mut env, t);
    for c in (0..n).step_by(50_000) {
        g += 1;
        env.apply(t, &mut (c..c + 50_000).filter(|i| i % 100 != 0).map(|i| (key8(i, 0), -1)).collect(), g).unwrap();
    }
    env.checkpoint(g, b"").unwrap();
    let (split, _, _, _) = shape(&mut env, t);
    assert!(split > full, "retractions grew the leaves ({full} -> {split})");
    env.set_frontier(g);
    let st = env.maintain_with(MaintBudget::UNLIMITED).unwrap();
    env.checkpoint(g, b"").unwrap();
    env.check_summaries(t).unwrap();
    let (leaves, internal, entries, bytes) = shape(&mut env, t);
    assert_eq!(entries, (n / 100) as usize, "dead entries left");
    assert_eq!(env.tree_count(t), (n / 100) as i64);
    // 2000 entries of 18 bytes fit in 3 leaves of 16 KiB
    assert!(leaves <= 8 && internal <= 2, "{leaves} leaves ({bytes} bytes) and {internal} internal nodes left of {split} leaves: {st:?}");
}

/// A pass short of budget says that it left work (the engine then makes its
/// next checkpoint due, so that an idle engine goes on reclaiming), and the
/// passes that follow finish it; a pass that did everything it found does
/// not say so.
#[test]
fn a_pass_short_of_budget_reports_work_left() {
    let tmp = TempDir::new("storage-maint-unfinished");
    let opts = EnvOptions { segment_bytes: 256 << 10, ..EnvOptions::default() };
    let (mut env, _) = Env::open(tmp.path(), opts).unwrap();
    let t = env.create_tree(Arc::new(CountSummarizer));
    let n = 50_000u64;
    env.apply(t, &mut (0..n).map(|i| (key8(i, 20), 1)).collect(), 1).unwrap();
    env.checkpoint(1, b"").unwrap();
    env.apply(t, &mut (0..n).filter(|i| i % 10 != 0).map(|i| (key8(i, 20), -1)).collect(), 2).unwrap();
    env.checkpoint(2, b"").unwrap();
    env.set_frontier(2);
    let budget = MaintBudget { compact: 64 << 10, gc: 64 << 10, memory: usize::MAX };
    let mut passes = 0;
    loop {
        let st = env.maintain_with(budget).unwrap();
        env.checkpoint(2, b"").unwrap();
        passes += 1;
        if !st.unfinished {
            break;
        }
        assert!(passes < 1000, "the passes do not finish: {st:?}");
    }
    assert!(passes > 1, "a pass of 64 KiB compacted a 1.6 MB tree");
    let (_, _, entries, _) = shape(&mut env, t);
    assert_eq!(entries as u64, n / 10, "dead entries left");
    check_live_accounting(&mut env);
    // a zero budget leaves the work it finds
    env.apply(t, &mut (0..n).filter(|i| i % 10 == 0).map(|i| (key8(i, 20), -1)).collect(), 3).unwrap();
    env.checkpoint(3, b"").unwrap();
    env.set_frontier(3);
    assert!(env.maintain_with(MaintBudget { compact: 0, gc: 0, memory: usize::MAX }).unwrap().unfinished);
}

/// The nodes a pass rewrites stay in the pool, dirty, until the checkpoint
/// writes them: a pass rewrites no more than the pool's target has room for
/// besides the dirty nodes it holds, whatever its byte budget, and says that
/// it left work, which the passes that follow do.
#[test]
fn a_pass_rewrites_what_the_pool_has_room_for() {
    let tmp = TempDir::new("storage-maint-memory");
    let cache = 1 << 20;
    let opts = EnvOptions { cache_bytes: cache, ..EnvOptions::default() };
    let (mut env, _) = Env::open(tmp.path(), opts).unwrap();
    let t = env.create_tree(Arc::new(CountSummarizer));
    let n = 100_000u64;
    for c in (0..n).step_by(10_000) {
        env.apply(t, &mut (c..c + 10_000).map(|i| (key8(i, 20), 1)).collect(), 1).unwrap();
        env.checkpoint(1, b"").unwrap();
    }
    for c in (0..n).step_by(10_000) {
        env.apply(t, &mut (c..c + 10_000).filter(|i| i % 10 != 0).map(|i| (key8(i, 20), -1)).collect(), 2).unwrap();
        env.checkpoint(2, b"").unwrap();
    }
    env.set_frontier(2);
    let mut passes = 0;
    loop {
        let st = env.maintain().unwrap();
        let dirty = env.dirty_bytes();
        // (the last node rewritten, and the path to it, may go beyond)
        assert!(dirty < cache + (256 << 10), "a pass left {dirty} bytes of dirty nodes in a pool of {cache}: {st:?}");
        env.checkpoint(2, b"").unwrap();
        passes += 1;
        if !st.unfinished {
            break;
        }
        assert!(passes < 100, "the passes do not finish: {st:?}");
    }
    assert!(passes > 1, "one pass compacted the whole tree within a pool of {cache} bytes");
    // nothing is left that a pass without limits would compact
    let st = env.maintain_with(MaintBudget::UNLIMITED).unwrap();
    assert_eq!(st.compacted, 0, "{st:?}");
    let (_, _, entries, _) = shape(&mut env, t);
    assert!(entries as u64 <= n / 10 + n / 100, "{entries} entries left");
}

