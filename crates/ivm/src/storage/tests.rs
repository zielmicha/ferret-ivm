//! Storage model test: random operation sequences checked against an
//! in-memory model of every tree's (key, GSN, weight) history.
//!
//! The operations are weighted inserts and deletes on several trees (plain
//! counts, and numeric / float / integer summaries over a value embedded in
//! the key) at increasing GSNs, retention frontier advances, tree creation
//! and drops, checkpoints, GC, clean reopens and simulated crashes:
//! - no final checkpoint;
//! - garbage after the durable end of the manifest or of the active segment,
//!   and stray segment files;
//! - a crash in the middle of a checkpoint: its nodes (partly) written but
//!   the manifest record missing or torn, or the record written but the
//!   segments it freed not yet deleted.
//!
//! Node sizes, segment size, retention and the buffer pool (down to a few
//! KB, so nodes are evicted all the time) are part of the generated case.
//! Point lookups are checked after every step; full verification compares
//! scans (current and AS OF retained GSNs), range and prefix scans, range
//! summaries, `nth`, the tree structure (key ranges, parent links,
//! `min_seg`) and the segment liveness accounting with the model. After a
//! crash the recovered state must equal the model as of the last checkpoint;
//! the operations since then are then replayed (as the engine replays its
//! input log) and must reproduce the state before the crash.
//!
//! Cases are generated by proptest: a failure shrinks to a minimal operation
//! sequence and is recorded under `proptest-regressions/`.
//! `PROPTEST_CASES=N` runs N cases (default 10), `PROPTEST_RNG_SEED=N` fixes
//! the seed. Long variant (longer sequences, 100 cases by default; the dev
//! profile keeps the storage layer's debug assertions on):
//! `cargo test -p ivm --lib storage::tests -- --ignored`.

