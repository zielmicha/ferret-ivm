/// Entries `ggg:uuuuu:<numeric text or NULL>`; summaries over the numeric.
struct TextNumSummarizer {
    spec: Vec<AggKind>,
}

fn text_num_of(key: &[u8]) -> Datum {
    let s = std::str::from_utf8(key).unwrap();
    let text = s.splitn(3, ':').nth(2).unwrap();
    if text == "NULL" { Datum::Null } else { Datum::numeric(pgnumeric::Numeric::parse(text).unwrap()) }
}

impl Summarizer for TextNumSummarizer {
    fn spec(&self) -> &[AggKind] {
        &self.spec
    }
    fn add_entry(&self, acc: &mut Summary, key: &[u8], weight: i64) -> Result<()> {
        acc.count += weight;
        let v = text_num_of(key);
        for (i, k) in self.spec.iter().enumerate() {
            k.add(&mut acc.aggs[i], &v, weight)?;
        }
        Ok(())
    }
    fn update_entry(&self, acc: &mut Summary, key: &[u8], before: i64, after: i64) -> Result<bool> {
        acc.count += after - before;
        let v = text_num_of(key);
        for (i, k) in self.spec.iter().enumerate() {
            if !k.update(&mut acc.aggs[i], &v, before, after)? {
                return Ok(false);
            }
        }
        Ok(true)
    }
}

/// After a checkpoint (nothing dirty): the live bytes recorded per segment
/// equal the bytes of the nodes reachable from the trees, and every segment
/// holding a reachable node exists.
fn check_live_accounting(env: &mut Env) {
    fn walk(env: &mut Env, ptr: NodePtr, live: &mut BTreeMap<u32, u64>) {
        let (loc, children) = match ptr {
            NodePtr::Disk(loc) => {
                let node = Node::decode(&env.segs.read(loc).unwrap()).unwrap();
                let ch = match node {
                    Node::Internal(ch) => ch.iter().map(|c| c.ptr).collect(),
                    Node::Leaf(_) => vec![],
                };
                (loc, ch)
            }
            NodePtr::Mem(id) => {
                let slot = env.slot(id);
                assert!(!slot.dirty, "dirty node after a checkpoint");
                let ch = match slot.node.as_deref().unwrap() {
                    Node::Internal(ch) => ch.iter().map(|c| c.ptr).collect(),
                    Node::Leaf(_) => vec![],
                };
                (slot.disk.unwrap(), ch)
            }
        };
        *live.entry(loc.seg).or_default() += loc.len as u64;
        for c in children {
            walk(env, c, live);
        }
    }
    let mut live: BTreeMap<u32, u64> = BTreeMap::new();
    let roots: Vec<NodePtr> = env.trees.values().filter_map(|t| t.root).collect();
    for r in roots {
        walk(env, r, &mut live);
    }
    let recorded: BTreeMap<u32, u64> = env.seg_live.iter().filter(|(_, (_, l))| *l > 0).map(|(id, (_, l))| (*id, *l)).collect();
    assert_eq!(live, recorded, "live bytes per segment");
    let files = env.segs.list().unwrap();
    for seg in live.keys() {
        assert!(files.contains(seg), "segment {seg} holds live nodes but is gone");
    }
}

/// Full-history model of one tree.
#[derive(Clone, Default)]
struct HistModel(BTreeMap<Vec<u8>, Vec<(Gsn, i64)>>);

impl HistModel {
    fn weight_at(&self, k: &[u8], t: Gsn) -> i64 {
        self.0.get(k).map(|h| h.iter().filter(|(g, _)| *g <= t).map(|(_, w)| w).sum()).unwrap_or(0)
    }
    fn total(&self, k: &[u8]) -> i64 {
        self.weight_at(k, Gsn::MAX)
    }
    fn truncate_after(&mut self, g: Gsn) {
        for h in self.0.values_mut() {
            h.retain(|(x, _)| *x <= g);
        }
        self.0.retain(|_, h| !h.is_empty());
    }
}

/// A checkpoint taken while a temporary tree exists, with nodes written
/// early and dirty ones, records neither the tree nor its bytes: after a
/// reopen the tree is gone, nothing is left unattached, and the segment
/// accounting has no bytes of it.
#[test]
fn checkpoints_do_not_record_temporary_trees() {
    let tmp = TempDir::new("storage-temp");
    let opts = EnvOptions { cache_bytes: 64 << 10, leaf_bytes: 1024, internal_bytes: 1024, segment_bytes: 256 << 10 };
    let (mut env, _) = Env::open(tmp.path(), opts.clone()).unwrap();
    let t = env.create_tree(Arc::new(CountSummarizer));
    let tmpt = env.create_temp_tree(Arc::new(CountSummarizer));
    assert!(tmpt >= TEMP_TREES);
    let key = |i: u64| i.to_be_bytes().to_vec();
    env.apply(t, &mut (0..2_000).map(|i| (key(i), 1)).collect(), 1).unwrap();
    env.apply(tmpt, &mut (0..20_000u64).map(|i| (key(i.wrapping_mul(0x9E37_79B9_7F4A_7C15)), 1)).collect(), 1).unwrap();
    assert!(!env.trees[&tmpt].seg_live.is_empty(), "nothing of the temporary tree was written early");
    env.checkpoint(1, b"one").unwrap();
    check_structure(&mut env, false, None);
    env.drop_tree(tmpt).unwrap();
    drop(env);
    let (mut env, rec) = Env::open(tmp.path(), opts).unwrap();
    assert_eq!(rec.unwrap().app, b"one");
    assert_eq!(env.tree_ids(), vec![t]);
    env.attach_tree(t, Arc::new(CountSummarizer)).unwrap();
    assert!(env.unattached_trees().is_empty());
    assert_eq!(env.tree_count(t), 2_000);
    check_structure(&mut env, false, None);
}

/// Dirty nodes are written early and evicted like clean ones: a batch many
/// times the cache leaves the buffer pool within the cache, lookups after it
/// sweep a few slots each (instead of every slot, finding nothing it may
/// evict), and none of it is durable before a checkpoint.
#[test]
fn dirty_data_larger_than_the_cache_is_evictable() {
    let tmp = TempDir::new("storage-dirty");
    let opts = EnvOptions { cache_bytes: 256 << 10, leaf_bytes: 2048, internal_bytes: 2048, segment_bytes: 1 << 20 };
    let (mut env, _) = Env::open(tmp.path(), opts.clone()).unwrap();
    let a = env.create_tree(Arc::new(CountSummarizer));
    let b = env.create_tree(Arc::new(CountSummarizer));
    let key = |i: u64| i.to_be_bytes().to_vec();
    env.apply(a, &mut (0..20_000).map(|i| (key(i), 1)).collect(), 1).unwrap();
    env.checkpoint(1, b"one").unwrap();
    // about 40 times the cache, in random key order, not checkpointed
    let mut ups: Vec<_> = (0..400_000u64).map(|i| (key(i.wrapping_mul(0x9E37_79B9_7F4A_7C15)), 1)).collect();
    env.apply(b, &mut ups, 2).unwrap();
    let bound = opts.cache_bytes + opts.cache_bytes / 16 + opts.leaf_bytes;
    assert!(env.resident_bytes() <= bound, "{} bytes resident after the batch", env.resident_bytes());
    assert!(env.dirty_bytes() <= opts.cache_bytes / 2, "{} dirty bytes after the batch", env.dirty_bytes());
    assert_eq!(env.tree_count(b), 400_000);
    let swept = env.stats().swept_slots;
    let mut x = 1u64;
    for _ in 0..10_000 {
        x = x.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        assert_eq!(env.get(a, &key((x >> 11) % 20_000)).unwrap().map(|h| h.total()), Some(1));
        assert!(env.resident_bytes() <= bound, "{} bytes resident", env.resident_bytes());
    }
    let per_get = (env.stats().swept_slots - swept) / 10_000;
    assert!(per_get <= 16, "{per_get} slots swept per lookup");
    check_structure(&mut env, false, None);
    // a crash: the early writes are not part of the checkpoint
    drop(env);
    let (mut env, rec) = Env::open(tmp.path(), opts).unwrap();
    assert_eq!(rec.unwrap().app, b"one");
    env.attach_tree(a, Arc::new(CountSummarizer)).unwrap();
    env.attach_tree(b, Arc::new(CountSummarizer)).unwrap();
    assert_eq!((env.tree_count(a), env.tree_count(b)), (20_000, 0));
    assert!(env.scan(b, Bound::Unbounded, Bound::Unbounded).unwrap().is_empty());
    check_structure(&mut env, false, None);
}

/// A tree built from entries in random order through sorted runs in
/// temporary trees (with several levels of merging): it holds the sums of
/// the entries' weights, the buffer pool stays within the cache, and the
/// temporary trees are gone.
#[test]
fn tree_builder_sorts_in_bounded_memory() {
    let tmp = TempDir::new("storage-builder");
    let opts = EnvOptions { cache_bytes: 64 << 10, leaf_bytes: 1024, internal_bytes: 1024, segment_bytes: 256 << 10 };
    let (mut env, _) = Env::open(tmp.path(), opts.clone()).unwrap();
    let t = env.create_tree(summarizer(Kind::Int));
    let mut b = TreeBuilder::with_limits(t, 7, 8 << 10, 3);
    let mut model: BTreeMap<Vec<u8>, i64> = BTreeMap::new();
    let mut rng = Rng::new(42);
    let bound = opts.cache_bytes + opts.cache_bytes / 16 + opts.leaf_bytes;
    for i in 0..30_000u64 {
        let u = if i < 5_000 { i } else { rng.below(20_000) };
        let k = format!("{:03}:{u:05}:{}:", u % 7, INT_VALUES[(u % 8) as usize]).into_bytes();
        // some entries cancel out across runs
        let w = if rng.chance(20) { -1 } else { 1 };
        *model.entry(k.clone()).or_default() += w;
        b.push(&mut env, k, w).unwrap();
        assert!(env.resident_bytes() <= bound, "{} bytes resident", env.resident_bytes());
    }
    b.finish(&mut env).unwrap();
    assert!(env.resident_bytes() <= bound, "{} bytes resident", env.resident_bytes());
    assert_eq!(env.tree_ids(), vec![t], "temporary trees left behind");
    let all = env.scan(t, Bound::Unbounded, Bound::Unbounded).unwrap();
    assert!(all.iter().all(|(_, h)| h.0.len() == 1 && h.0[0].0 == 7), "histories other than one change at the builder's GSN");
    let got: Vec<(Vec<u8>, i64)> = all.into_iter().map(|(k, h)| (k.to_vec(), h.total())).collect();
    let want: Vec<(Vec<u8>, i64)> = model.into_iter().filter(|(_, w)| *w != 0).collect();
    assert!(got == want, "built tree differs from the model");
    env.check_summaries(t).unwrap();
    check_structure(&mut env, false, None);
}

/// Random updates with a moving retention frontier, AS OF reads at every
/// retained time, checkpoints, crashes (reopen without a checkpoint), GC
/// and a cache small enough to evict constantly: reads must equal the
/// model, summaries their recomputation.
#[test]
fn time_travel_crashes_and_gc_against_model() {
    for seed in [0x9E3779B97F4A7C15u64, 0xD1B54A32D192ED03, 0x2545F4914F6CDD1D] {
        let tmp = TempDir::new(&format!("storage-tt-{seed:x}"));
        let dir = tmp.path().to_path_buf();
        let opts = EnvOptions { cache_bytes: 16 << 10, leaf_bytes: 400, internal_bytes: 300, segment_bytes: 16 << 10 };
        let spec = vec![AggKind::SumNumeric, AggKind::Min, AggKind::Max, AggKind::CountNonNull];
        let summ: Arc<dyn Summarizer> = Arc::new(TextNumSummarizer { spec: spec.clone() });
        let (mut env, _) = Env::open(&dir, opts.clone()).unwrap();
        let tree = env.create_tree(summ.clone());
        let retention = 7;
        let mut rng = Rng::new(seed);
        let mut model = HistModel::default();
        let mut ckpt: Option<(Gsn, HistModel)> = None;
        let mut gsn: Gsn = 0;
        let values = ["1", "1.0", "2.50", "-3", "0", "7.25", "NULL", "10"];
        for step in 0..1500 {
            gsn += 1;
            env.set_frontier(gsn.saturating_sub(retention));
            let n = 1 + rng.below(if step % 100 == 0 { 300 } else { 10 });
            let mut ups = Vec::new();
            for _ in 0..n {
                let k = format!("{:03}:{:05}:{}", rng.below(5), rng.below(300), values[rng.below(8) as usize]).into_bytes();
                let cur = model.total(&k);
                let w = if cur > 0 && rng.below(2) == 0 { -cur } else { 1 + rng.below(2) as i64 };
                ups.push((k.clone(), w));
                let h = model.0.entry(k).or_default();
                match h.last_mut() {
                    Some((g, lw)) if *g == gsn => *lw += w,
                    _ => h.push((gsn, w)),
                }
            }
            env.apply(tree, &mut ups, gsn).unwrap();
            let frontier = env.frontier();
            // point reads at random retained times
            for _ in 0..5 {
                let t = frontier + rng.below(gsn - frontier + 1);
                let k = format!("{:03}:{:05}:{}", rng.below(5), rng.below(300), values[rng.below(8) as usize]).into_bytes();
                let got = env.get(tree, &k).unwrap().map(|h| h.weight(ReadAt::AsOf(t))).unwrap_or(0);
                assert_eq!(got, model.weight_at(&k, t), "seed {seed:x} step {step}: {k:?} as of {t}");
            }
            if step % 25 == 0 {
                // full scan as of a retained time
                let t = frontier + rng.below(gsn - frontier + 1);
                let got: Vec<(Vec<u8>, i64)> = env
                    .scan(tree, Bound::Unbounded, Bound::Unbounded)
                    .unwrap()
                    .into_iter()
                    .map(|(k, h)| (k.to_vec(), h.weight(ReadAt::AsOf(t))))
                    .filter(|(_, w)| *w != 0)
                    .collect();
                let want: Vec<(Vec<u8>, i64)> =
                    model.0.keys().map(|k| (k.clone(), model.weight_at(k, t))).filter(|(_, w)| *w != 0).collect();
                assert_eq!(got, want, "seed {seed:x} step {step}: scan as of {t}");
                env.check_summaries(tree).unwrap();
                let mut s = Summary::empty(&spec);
                for k in model.0.keys() {
                    summ.add_entry(&mut s, k, model.total(k)).unwrap();
                }
                assert!(env.tree_summary(tree).exact_eq(&s), "seed {seed:x} step {step}: tree summary");
            }
            match rng.below(40) {
                0..=2 => {
                    env.checkpoint(gsn, format!("{gsn}").as_bytes()).unwrap();
                    check_live_accounting(&mut env);
                    ckpt = Some((gsn, model.clone()));
                }
                3 => {
                    let b = 1 + rng.below(40_000);
                    env.maintain_with(MaintBudget { compact: b, gc: b, memory: usize::MAX }).unwrap();
                }
                4 => {
                    // crash: everything after the last checkpoint is lost
                    drop(env);
                    let (e, rec) = Env::open(&dir, opts.clone()).unwrap();
                    env = e;
                    match &ckpt {
                        Some((g, m)) => {
                            let rec = rec.expect("recovered checkpoint");
                            assert_eq!(rec.gsn, *g);
                            assert_eq!(rec.app, format!("{g}").into_bytes());
                            env.attach_tree(tree, summ.clone()).unwrap();
                            gsn = *g;
                            model = m.clone();
                        }
                        None => {
                            assert!(rec.is_none());
                            let t = env.create_tree(summ.clone());
                            assert_eq!(t, tree);
                            gsn = 0;
                            model = HistModel::default();
                        }
                    }
                    env.set_frontier(gsn.saturating_sub(retention));
                    model.truncate_after(gsn);
                }
                _ => {}
            }
        }
        // garbage collection keeps the store bounded
        // garbage collection (one sparse segment per round; relocation
        // rewrites paths to the root, so it never quite settles) keeps the
        // store within a small factor of its live data
        for _ in 0..300 {
            env.maintain().unwrap();
            gsn += 1;
            env.checkpoint(gsn, b"").unwrap();
            check_live_accounting(&mut env);
        }
        let st = env.stats();
        let live: u64 = st.segments.iter().map(|s| s.2).sum();
        let total: u64 = st.segments.iter().map(|s| s.1).sum();
        assert!(total <= 4 * live + 4 * opts.segment_bytes, "{st:?}");
    }
}


